"""Render uos-catalogue.json as an idempotent SQL data migration.

Usage: python supabase/seed/catalogue_to_sql.py supabase/seed/uos-catalogue.json <out.sql>
Catalogue changes after launch go in a new migration, never by editing an applied one.
"""

import json
import sys
from pathlib import Path


def q(value: str | None) -> str:
    return "null" if value is None else "'" + value.replace("'", "''") + "'"


def arr(values: list[str]) -> str:
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


src, out = Path(sys.argv[1]), Path(sys.argv[2])
cat = json.loads(src.read_text(encoding="utf-8"))
u = cat["university"]
uni = f"(select id from public.universities where slug = {q(u['slug'])})"

lines = [
    "-- Generated by supabase/seed/catalogue_to_sql.py from uos-catalogue.json. Do not edit by hand.",
    "",
    "insert into public.universities (slug, name, short_name, city, roll_no_regex, "
    "registration_no_regex, is_live)",
    f"values ({q(u['slug'])}, {q(u['name'])}, {q(u['short_name'])}, {q(u['city'])}, "
    f"{q(u['roll_no_regex'])}, {q(u['registration_no_regex'])}, true)",
    "on conflict (slug) do nothing;",
    "",
    "insert into public.auth_providers (mail_host, live)",
    "values ('google', true), ('microsoft', true), ('other', true)",
    "on conflict (mail_host) do nothing;",
    "",
]
for c in cat["campuses"]:
    lines += [
        "insert into public.campuses (university_id, name, is_main)",
        f"values ({uni}, {q(c['name'])}, {str(c['is_main']).lower()})",
        "on conflict (university_id, name) do nothing;",
    ]
main = next(c["name"] for c in cat["campuses"] if c["is_main"])
main_campus = f"(select id from public.campuses where name = {q(main)} and university_id = {uni})"
for d in u["domains"]:
    lines += [
        "insert into public.university_domains (university_id, campus_id, domain, student_only, mail_host)",
        f"values ({uni}, {main_campus}, {q(d)}, true, 'google')",
        "on conflict (domain) do nothing;",
    ]
lines.append("")

for f in cat["faculties"]:
    for d in f["departments"]:
        lines += [
            "insert into public.departments (university_id, campus_id, name, short_code, faculty, aliases)",
            f"values ({uni}, {main_campus}, {q(d['name'])}, {q(d['short_code'])}, {q(f['name'])}, "
            f"{arr(d['aliases'])})",
            "on conflict (university_id, short_code) do nothing;",
        ]
        if d["programs"]:
            dept = (
                f"(select id from public.departments where short_code = {q(d['short_code'])} "
                f"and university_id = {uni})"
            )
            rows = ",\n  ".join(
                f"({dept}, {q(p['name'])}, '{p['level']}', {p['duration_semesters']})"
                for p in d["programs"]
            )
            lines += [
                "insert into public.programs (department_id, name, level, duration_semesters) values",
                f"  {rows}",
                "on conflict (department_id, name) do nothing;",
            ]
        lines.append("")

out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"Wrote {out}")
